    static readonly Dictionary<(string, bool, bool), Texture2D> cache = [];

    /// <summary>The icon of an achievement, earned or not; a hidden one not yet earned shows nothing of itself.</summary>
    public static Texture2D Of(AchievementDef a, bool earned)
    {
        var secret = a.Hidden && !earned;
        if (cache.TryGetValue((a.Id, earned, secret), out var t)) return t;
        return cache[(a.Id, earned, secret)] = ImageTexture.CreateFromImage(Draw(secret ? "unknown" : a.Icon, earned));
    }

    static Image Draw(string icon, bool earned)
    {
        var img = Image.CreateEmpty(Side * Scale, Side * Scale, false, Image.Format.Rgba8);
        void Dot(int x, int y, Color c) => img.FillRect(new Rect2I(x * Scale, y * Scale, Scale, Scale), c);
        // The badge: an octagon cut 6 pixels at each corner, a dark outline, a fill lit from the top.
        Color top = earned ? Palette.Accent.Lightened(0.2f) : Palette.Raised.Lightened(0.12f);
        Color bottom = earned ? Palette.Accent.Darkened(0.35f) : Palette.Raised.Darkened(0.1f);
        bool Inside(int x, int y, int cut) => x >= 0 && y >= 0 && x < Side && y < Side
            && x + y >= cut && (Side - 1 - x) + y >= cut && x + (Side - 1 - y) >= cut && (Side - 1 - x) + (Side - 1 - y) >= cut;
        for (var y = 0; y < Side; y++)
        {
            for (var x = 0; x < Side; x++)
            {
                if (!Inside(x, y, 6)) continue;
                var edge = !Inside(x - 1, y, 6) || !Inside(x + 1, y, 6) || !Inside(x, y - 1, 6) || !Inside(x, y + 1, 6);
                Dot(x, y, edge ? Palette.Bg : top.Lerp(bottom, y / (Side - 1f)));
            }
        }
        var ink = earned ? Palette.Bg : Palette.Muted with { A = 0.55f };
        if (icon.StartsWith("race:", StringComparison.Ordinal) && Enum.TryParse<Faction>(icon[5..], out var race))
        {
            // The race's emblem, 16 pixels, in the middle: its own colors once earned, the badge's ink until then.
            var emblem = Logos.EmblemImage(race, 1);
            for (var y = 0; y < 16; y++)
            {
                for (var x = 0; x < 16; x++)
                {
                    var c = emblem.GetPixel(x, y);
                    if (c.A > 0) Dot(4 + x, 4 + y, earned ? c : ink with { A = c.A * ink.A });
                }
            }
            return img;
        }
        var glyph = Glyphs.GetValueOrDefault(icon) ?? Glyphs["star"];
        for (var y = 0; y < 12; y++)
        {
            for (var x = 0; x < 12; x++)
            {
                if (glyph[y][x] == '#') Dot(6 + x, 6 + y, ink);
            }
        }
        return img;
    }
